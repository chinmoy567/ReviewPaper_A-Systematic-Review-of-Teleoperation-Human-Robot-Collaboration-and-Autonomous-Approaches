"""Recompute every Results table from data/extraction_table.csv only.

Usage:  python data/recompute_tables.py   -> writes data/recomputed_tables.md
Primary codings (author decision, 2026-11-08): validation_strict (mock/lab facilities = Partial/Bench)
and env_realism_limitation (literal author-stated rule). validation_lenient and env_realism_broad are
sensitivity checks. validation_clean == validation_strict. manuscript_* columns hold the manuscript's
own labels (Sec. IV lists, Sec. 6B) for comparison only.
"""
import csv, os
from collections import Counter
try:
    from scipy.stats import fisher_exact
except Exception:  # scipy optional
    fisher_exact = None

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, 'extraction_table.csv'), encoding='utf-8')))
coded = [r for r in rows if r['coding_status'] == 'CODED']
N_all, N = len(rows), len(coded)
SENS = ['visual', 'thermal', 'depth', 'lidar', 'gps', 'imu', 'acoustic', 'gas', 'rf', 'physio', 'none']
MODES = ['Teleoperation', 'Supervisory Control', 'Shared-Collaborative Control', 'Fully Autonomous']
VALS = ['Simulation only', 'Real-world field test', 'Partial', 'Prototype bench test']
PLATS = ['UAV', 'UGV', 'Legged', 'UUV / USV', 'Hybrid / Multi-Platform', 'Abstract / Unspecified']
CLU = ['multi-robot coordination', 'single-robot navigation', 'perception-driven', 'platform-architecture']
ARCH = ['PC/Offline', 'Onboard/Edge', 'Hybrid', 'Cloud', 'Not reported']
SCEN = ['Generic/Unspecified', 'Underground/Mine/Tunnel/Cave', 'Earthquake/Structural Collapse',
        'Wilderness/Mountain/Forest', 'Maritime/Water', 'Wildfire/Fire', 'Other (single-occurrence hazard)']
FIELD = 'Real-world field test'
out = []

def pct(a, b):
    return f"{a}/{b} ({100*a/b:.1f}%)" if b else f"{a}/0"

def dist(title, key, order, data):
    c = Counter(r[key] for r in data)
    out.append(f"\n### {title} (n = {len(data)})\n\n| Category | n (%) |\n|---|---|")
    for k in order + sorted(set(c) - set(order)):
        out.append(f"| {k} | {pct(c.get(k, 0), len(data))} |")

def xtab(title, rk, ro, ck, co, data):
    out.append(f"\n### {title} (n = {len(data)})\n")
    out.append(f"| {rk} \\ {ck} | " + ' | '.join(co) + ' | Total |')
    out.append('|' + '---|' * (len(co) + 2))
    for a in ro:
        sub = [r for r in data if r[rk] == a]
        if sub:
            out.append(f"| {a} | " + ' | '.join(str(sum(r[ck] == b for r in sub)) for b in co) + f" | {len(sub)} |")
    out.append('| **Total** | ' + ' | '.join(str(sum(r[ck] == b for r in data)) for b in co) + f" | {len(data)} |")

def rate(data, key, val=FIELD):
    return pct(sum(r[key] == val for r in data), len(data))

out.append(f"# Recomputed tables\n\nSource: `data/extraction_table.csv` (generated by `data/recompute_tables.py`). "
           f"Rows coded from PDFs: **{N} of {N_all}**. Primary codings: `validation_strict`, `env_realism_limitation` (literal).")

dist('Table V. Mode', 'mode_clean', MODES, coded)
dist('Table VI. Platform', 'platform_clean', PLATS, coded)
xtab('Table VII. Mode x Platform', 'mode_clean', MODES, 'platform_clean', PLATS, coded)
out.append(f"\n### Table VIII. Sensor prevalence (multi-select, n = {N})\n\n| Modality | n (%) |\n|---|---|")
for s in SENS:
    out.append(f"| {s} | {pct(sum(int(r['s_'+s] or 0) for r in coded), N)} |")
dist('Table IX. Architecture', 'architecture_clean', ARCH, coded)
fa = [r for r in coded if r['mode_clean'] == 'Fully Autonomous']
hm = [r for r in coded if r['mode_clean'] != 'Fully Autonomous']
for vk, lab in [('validation_strict', 'STRICT (primary)'), ('validation_lenient', 'LENIENT (sensitivity)')]:
    out.append(f"\n## Validation coding: {lab}")
    dist(f'Table X. Validation, {lab}', vk, VALS, coded)
    xtab(f'Table XI. Mode x Validation, {lab}', 'mode_clean', MODES, vk, VALS, coded)
    xtab(f'Platform x Validation, {lab}', 'platform_clean', PLATS, vk, VALS, coded)
    xtab(f'FA cluster x Validation, {lab}', 'fa_cluster', CLU, vk, VALS, fa)
dist('Table XII. Scenario', 'scenario_clean', SCEN, coded)

gen = [r for r in coded if r['scenario_clean'] == 'Generic/Unspecified']
spec = [r for r in coded if r['scenario_clean'] != 'Generic/Unspecified']
for ek, lab in [('env_realism_limitation', 'LITERAL author-stated rule (primary)'),
                ('env_realism_broad', 'BROAD rule (any real-world-condition gap; sensitivity)')]:
    out.append(f"\n### Environmental realism, {lab}\n")
    out.append(f"- All papers: Y = {rate(coded, ek, 'Y')}")
    out.append(f"- Generic/Unspecified: Y = {rate(gen, ek, 'Y')}; hazard-specific: Y = {rate(spec, ek, 'Y')}")
    out.append(f"- N codes (refs): {', '.join(r['ref_N'] for r in coded if r[ek] == 'N')}")
out.append("- Literal-rule borderline codes (refs): " + ', '.join(r['ref_N'] for r in coded if r['env_realism_confidence'].startswith('borderline')))

xtab('Human role modelled x Mode', 'mode_clean', MODES, 'human_role_modelled', ['Y', 'N'], coded)

out.append(f"\n### VDR score (vd + rp, 2-6) by mode (n = {N})\n\n| Mode | n | VDR distribution | mean VDR | mean vd | mean rp | stat = Y |\n|---|---|---|---|---|---|---|")
for m in MODES:
    sub = [r for r in coded if r['mode_clean'] == m]
    if sub:
        v = Counter(int(r['vdr']) for r in sub)
        out.append(f"| {m} | {len(sub)} | {dict(sorted(v.items()))} | {sum(int(r['vdr']) for r in sub)/len(sub):.2f} | "
                   f"{sum(int(r['vd']) for r in sub)/len(sub):.2f} | {sum(int(r['rp']) for r in sub)/len(sub):.2f} | {sum(r['stat']=='Y' for r in sub)} |")

out.append("\n### Primary contrast: Fully Autonomous vs human-in-mission modes (Teleop + Supervisory + Shared)\n")
for vk in ['validation_strict', 'validation_lenient']:
    a = sum(r[vk] == FIELD for r in fa); c = sum(r[vk] == FIELD for r in hm)
    p = f"{fisher_exact([[a, len(fa)-a], [c, len(hm)-c]])[1]:.4f}" if fisher_exact else 'scipy unavailable'
    out.append(f"- **{vk}**: FA field-tested {pct(a, len(fa))} vs human-in-mission {pct(c, len(hm))}; Fisher exact two-sided p = {p}")
    for m in MODES:
        out.append(f"  - {m}: {rate([r for r in coded if r['mode_clean'] == m], vk)}")
    for pl in ['UAV', 'Hybrid / Multi-Platform']:
        out.append(f"  - {pl}: {rate([r for r in coded if r['platform_clean'] == pl], vk)}")
a = sum(r['human_role_modelled'] == 'Y' for r in fa); c = sum(r['human_role_modelled'] == 'Y' for r in hm)
out.append(f"- Human role modelled in tested setup: FA {pct(a, len(fa))} vs human-in-mission modes {pct(c, len(hm))}")

out.append("\n### Agreement with manuscript labels\n")
for k in ['mode_agrees', 'platform_agrees', 'fa_cluster_agrees']:
    out.append(f"- {k}: {dict(Counter(r[k] for r in coded if r[k]))}")

open(os.path.join(HERE, 'recomputed_tables.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('\n'.join(out))
