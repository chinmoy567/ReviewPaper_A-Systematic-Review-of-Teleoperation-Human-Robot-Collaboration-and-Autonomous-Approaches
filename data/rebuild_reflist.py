"""Regenerate the APA reference-list block in Sec. 15 from data/references.py, and check that
every in-text author-date citation in the manuscript resolves to exactly one entry and vice versa."""
import re, sys
sys.path.insert(0, "data")
from references import REFS, sort_key

P = "SAR_review_master_document.md"
s = open(P, encoding="utf-8").read()
REG = [("### II. METHODOLOGY", "## 10."), ("### III. RESULTS", "## 11."), ("### IV. TAXONOMY", "## 12."),
       ("### V. DISCUSSION", "## 13."), ("### I. INTRODUCTION", "### Sourcing notes"), ("### TITLE AND AUTHORS", "## 15.")]
txt = "\n".join(s[s.index(a):s.index(b, s.index(a))] for a, b in REG)

used, forms = set(), {}
for k, (a, y, _) in REFS.items():
    pats = [f"{a} ({y})", f"{a}, {y}", f"{a.replace(' and ', ' & ')}, {y}", f"{a} [{y}]".replace(" [", ", ")]
    if a == "Cohen":
        pats.append("Cohen, 1960")
    if any(p_ in txt for p_ in pats):
        used.add(k)
missing_in_list = []
# every "(Name..., YEAR)" style token must be a known form
known = {f"{a.replace(' and ', ' & ')}, {y}" for a, y, _ in REFS.values()} | {f"{a}, {y}" for a, y, _ in REFS.values()}
for m in re.finditer(r"([A-Z][A-Za-zÀ-ž'\-\. ]+?(?: et al\.| & [A-Z][A-Za-zÀ-ž\-]+)?, (?:19|20)\d\d[a-c]?)", txt):
    t = m.group(1).strip()
    t = re.sub(r"^(?:and|see|e\.g\.,) ", "", t)
    if t not in known and not re.match(r"^(?:Section|Table|Fig)", t):
        missing_in_list.append(t)
unused = [k for k in REFS if k not in used]
print("cited entries:", len(used), "of", len(REFS))
print("entries not cited:", unused)
print("in-text forms not in list (check):", sorted(set(missing_in_list))[:40])

bib = "\n\n".join(REFS[k][2] for k in sorted(used, key=sort_key))
start = s.index("\n### Reference list for the manuscript (APA author-date")
end = s.index("\n## 16. Revision log")
block = ("\n### Reference list for the manuscript (APA author-date, *Journal of Field Robotics*), 2026-11-08\n\n"
         "Supersedes the numbered list above for the manuscript (the numbered list is kept as the working record). "
         "In-text citations in Secs. 9–14 use these author-date forms. Regenerated by `data/rebuild_reflist.py` from `data/references.py`.\n\n"
         + bib + "\n")
s = s[:start] + block + s[end:]
open(P, "w", encoding="utf-8").write(s)
