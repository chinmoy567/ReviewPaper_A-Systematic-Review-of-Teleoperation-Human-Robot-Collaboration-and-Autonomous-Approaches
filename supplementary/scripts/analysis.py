"""Reproducible analysis for the SAR robotics review (all Results numbers).

Input : data/extraction_table.csv (39 rows, rebuilt from PDFs 2026-11-08)
        data/reliability_blind_codes.csv (post hoc AI blind codes)
Output: data/analysis_output.md
Run   : python data/analysis.py
All tests are exploratory/post hoc (see manuscript Sec. II-I).
"""
import csv, collections, math
import numpy as np
from scipy.stats import fisher_exact, mannwhitneyu
from scipy.stats.contingency import odds_ratio

rows = list(csv.DictReader(open("data/extraction_table.csv", encoding="utf-8")))
assert len(rows) == 39
FA, TELE, SUP, SHR = "Fully Autonomous", "Teleoperation", "Supervisory Control", "Shared-Collaborative Control"
FIELD = "Real-world field test"
out = []
P = out.append


def wilson(k, n, z=1.959964):
    if n == 0:
        return (float("nan"),) * 2
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0, c - h) * 100, min(1, c + h) * 100


def fmt(k, n):
    lo, hi = wilson(k, n)
    return f"{k}/{n} ({100*k/n:.1f}%; 95% CI {lo:.1f}–{hi:.1f})"


def contrast(label, a, n1, b, n2):
    t = [[a, n1 - a], [b, n2 - b]]
    p = fisher_exact(t)[1]
    orr = odds_ratio(t, kind="conditional")
    ci = orr.confidence_interval(0.95)
    P(f"| {label} | {fmt(a,n1)} | {fmt(b,n2)} | {orr.statistic:.2f} ({ci.low:.3f}–{ci.high:.2f}) | {p:.4f} |")
    return p


def rxc_perm_p(table, nperm=200000, seed=1):
    """Monte Carlo exact (Freeman–Halton-type) test: probability of tables as or less likely, via permutation of labels."""
    rng = np.random.default_rng(seed)
    table = np.asarray(table)
    rowlab = np.repeat(np.arange(table.shape[0]), table.sum(1))
    collab = np.concatenate([np.repeat(np.arange(table.shape[1]), table[i]) for i in range(table.shape[0])])

    def stat(r, c):  # Pearson chi-square as discrepancy measure
        t = np.zeros(table.shape)
        np.add.at(t, (r, c), 1)
        e = t.sum(1, keepdims=True) * t.sum(0, keepdims=True) / t.sum()
        with np.errstate(divide="ignore", invalid="ignore"):
            return np.nansum((t - e) ** 2 / e)

    s0 = stat(rowlab, collab)
    ge = 0
    for _ in range(nperm):
        ge += stat(rowlab, rng.permutation(collab)) >= s0 - 1e-12
    return (ge + 1) / (nperm + 1)


def marg(col, title, order=None):
    c = collections.Counter(r[col] for r in rows)
    keys = order or [k for k, _ in c.most_common()]
    P(f"\n### {title}\n\n| Category | n | % (95% CI) |\n|---|---|---|")
    for k in keys:
        lo, hi = wilson(c[k], 39)
        P(f"| {k} | {c[k]} | {100*c[k]/39:.1f} ({lo:.1f}–{hi:.1f}) |")


def xtab(rcol, ccol, title, rorder, corder):
    P(f"\n### {title}\n\n| | " + " | ".join(corder) + " | Total |\n|" + "---|" * (len(corder) + 2))
    for rv in rorder:
        sub = [r for r in rows if r[rcol] == rv]
        P(f"| {rv} | " + " | ".join(str(sum(r[ccol] == cv for r in sub)) for cv in corder) + f" | {len(sub)} |")
    P("| **Total** | " + " | ".join(str(sum(r[ccol] == cv for r in rows)) for cv in corder) + " | 39 |")


MODES = [TELE, SUP, SHR, FA]
VAL = ["Simulation only", "Partial", "Prototype bench test", FIELD]
PLAT = ["UAV", "UGV", "Legged", "UUV / USV", "Hybrid / Multi-Platform", "Abstract / Unspecified"]

P("# Analysis output (generated by data/analysis.py; do not edit by hand)\n")
marg("mode_clean", "Autonomy/HRI mode", MODES)
marg("platform_clean", "Platform", PLAT)
marg("validation_strict", "Validation (strict, primary)", VAL)
marg("validation_lenient", "Validation (lenient, sensitivity)", VAL)
marg("architecture_clean", "Computational architecture")
marg("scenario_clean", "Disaster scenario")
P("\n### Sensor prevalence (non-exclusive)\n\n| Modality | n | % (95% CI) |\n|---|---|---|")
for f in ["s_visual", "s_imu", "s_lidar", "s_gps", "s_none", "s_thermal", "s_depth", "s_gas", "s_acoustic", "s_rf", "s_physio"]:
    k = sum(r[f] == "1" for r in rows)
    lo, hi = wilson(k, 39)
    P(f"| {f[2:]} | {k} | {100*k/39:.1f} ({lo:.1f}–{hi:.1f}) |")

xtab("mode_clean", "platform_clean", "Mode × platform", MODES, PLAT)
xtab("mode_clean", "validation_strict", "Mode × validation (strict)", MODES, VAL)
xtab("mode_clean", "validation_lenient", "Mode × validation (lenient)", MODES, VAL)
xtab("platform_clean", "validation_strict", "Platform × validation (strict)", PLAT, VAL)
fa_rows = [r for r in rows if r["mode_clean"] == FA]
P("\n### FA cluster × validation (strict)\n\n| Cluster | n | Sim only | Partial | Bench | Field |\n|---|---|---|---|---|---|")
for cl in sorted(set(r["fa_cluster"] for r in fa_rows)):
    s = [r for r in fa_rows if r["fa_cluster"] == cl]
    P(f"| {cl} | {len(s)} | " + " | ".join(str(sum(r['validation_strict'] == v for r in s)) for v in VAL) + " |")

P("\n### Per-mode rates\n\n| Mode | Field (strict) | Field (lenient) | Any physical test | Human role modeled | Mean VD | Mean RP | Mean VDR |\n|---|---|---|---|---|---|---|---|")
for m in MODES + ["ALL"]:
    s = rows if m == "ALL" else [r for r in rows if r["mode_clean"] == m]
    n = len(s)
    f1 = sum(r["validation_strict"] == FIELD for r in s)
    f2 = sum(r["validation_lenient"] == FIELD for r in s)
    ph = sum(r["validation_strict"] != "Simulation only" for r in s)
    hr = sum(r["human_role_modelled"] == "Y" for r in s)
    vd = np.mean([int(r["vd"]) for r in s]); rp = np.mean([int(r["rp"]) for r in s]); vdr = np.mean([int(r["vdr"]) for r in s])
    P(f"| {m} | {fmt(f1,n)} | {fmt(f2,n)} | {fmt(ph,n)} | {hr}/{n} | {vd:.2f} | {rp:.2f} | {vdr:.2f} |")

P("\n### Platform rates\n\n| Platform | Field (strict) | Field (lenient) | Sim only |\n|---|---|---|---|")
for pl in PLAT:
    s = [r for r in rows if r["platform_clean"] == pl]
    n = len(s)
    P(f"| {pl} | {fmt(sum(r['validation_strict']==FIELD for r in s),n)} | {fmt(sum(r['validation_lenient']==FIELD for r in s),n)} | {fmt(sum(r['validation_strict']=='Simulation only' for r in s),n)} |")

# --- contrasts
hm = [r for r in rows if r["mode_clean"] != FA]
ts = [r for r in rows if r["mode_clean"] in (TELE, SUP)]
P("\n### Contrasts (two-sided Fisher exact; conditional MLE OR with exact 95% CI; exploratory)\n\n| Contrast | Group 1 | Group 2 | OR (95% CI) | p |\n|---|---|---|---|---|")
cnt = lambda s, col, val: sum(r[col] == val for r in s)
contrast("Field, strict: FA vs human-in-mission", cnt(fa_rows, "validation_strict", FIELD), 27, cnt(hm, "validation_strict", FIELD), 12)
contrast("Field, lenient: FA vs human-in-mission", cnt(fa_rows, "validation_lenient", FIELD), 27, cnt(hm, "validation_lenient", FIELD), 12)
contrast("Field, strict: FA vs Tele+Sup", cnt(fa_rows, "validation_strict", FIELD), 27, cnt(ts, "validation_strict", FIELD), 9)
contrast("Field, lenient: FA vs Tele+Sup", cnt(fa_rows, "validation_lenient", FIELD), 27, cnt(ts, "validation_lenient", FIELD), 9)
phys = lambda s: sum(r["validation_strict"] != "Simulation only" for r in s)
contrast("Any physical test: FA vs human-in-mission", phys(fa_rows), 27, phys(hm), 12)
vd3 = lambda s: sum(r["vd"] == "3" for r in s)
contrast("VD = 3 (mission-representative site): FA vs human-in-mission", vd3(fa_rows), 27, vd3(hm), 12)
uav = [r for r in rows if r["platform_clean"] == "UAV"]; hyb = [r for r in rows if r["platform_clean"] == "Hybrid / Multi-Platform"]
contrast("Field, strict: UAV vs Hybrid (descriptive)", cnt(uav, "validation_strict", FIELD), 13, cnt(hyb, "validation_strict", FIELD), 7)
gen = [r for r in rows if r["scenario_clean"].startswith("Generic")]; spec = [r for r in rows if not r["scenario_clean"].startswith("Generic")]
contrast("Env-realism limitation (literal): Generic vs hazard-specific", cnt(gen, "env_realism_limitation", "Y"), len(gen), cnt(spec, "env_realism_limitation", "Y"), len(spec))

u = mannwhitneyu([int(r["vd"]) for r in fa_rows], [int(r["vd"]) for r in hm], alternative="two-sided")
P(f"\nValidation depth (VD 1–3), FA vs human-in-mission: median {np.median([int(r['vd']) for r in fa_rows]):.0f} vs {np.median([int(r['vd']) for r in hm]):.0f}; mean {np.mean([int(r['vd']) for r in fa_rows]):.2f} vs {np.mean([int(r['vd']) for r in hm]):.2f}; Mann–Whitney U = {u.statistic:.1f}, p = {u.pvalue:.4f}.")
u2 = mannwhitneyu([int(r["rp"]) for r in fa_rows], [int(r["rp"]) for r in hm], alternative="two-sided")
P(f"Reproducibility (RP 1–3), FA vs human-in-mission: mean {np.mean([int(r['rp']) for r in fa_rows]):.2f} vs {np.mean([int(r['rp']) for r in hm]):.2f}; Mann–Whitney p = {u2.pvalue:.4f}.")

for col, lab in [("validation_strict", "strict"), ("validation_lenient", "lenient")]:
    t = [[sum(r["mode_clean"] == m and r[col] == FIELD for r in rows), sum(r["mode_clean"] == m and r[col] != FIELD for r in rows)] for m in MODES]
    P(f"4 × 2 mode × field ({lab}) Monte Carlo exact test (200,000 permutations, seed 1): p = {rxc_perm_p(t):.4f}; table {t}.")

lit = cnt(rows, "env_realism_limitation", "Y"); br = cnt(rows, "env_realism_broad", "Y")
P(f"\nEnvironmental-realism limitation, literal rule: {fmt(lit,39)}; broad rule: {fmt(br,39)}.")
P(f"Generic: literal {fmt(cnt(gen,'env_realism_limitation','Y'),len(gen))}; hazard-specific: literal {fmt(cnt(spec,'env_realism_limitation','Y'),len(spec))}.")
P(f"Generic: broad {fmt(cnt(gen,'env_realism_broad','Y'),len(gen))}; hazard-specific: broad {fmt(cnt(spec,'env_realism_broad','Y'),len(spec))}.")
P(f"Public code/data link (RP = 3): {cnt(rows,'rp','3')}/39; baseline or variance reported: {cnt(rows,'stat','Y')}/39.")

# --- sensitivity analyses on primary contrast (any physical test, field strict, field lenient)
P("\n### Sensitivity analyses (FA vs human-in-mission)\n\n| Analysis | n (FA / HM) | Field strict FA vs HM, p | Field lenient FA vs HM, p | Any physical test FA vs HM, p |\n|---|---|---|---|---|")


def sens(label, rs, modekey="mode_clean"):
    f = [r for r in rs if r[modekey] == FA]; h = [r for r in rs if r[modekey] != FA]
    if not f or not h:
        P(f"| {label} | {len(f)} / {len(h)} | not estimable | not estimable | not estimable |"); return
    cells = []
    for col, val, neg in [("validation_strict", FIELD, False), ("validation_lenient", FIELD, False), ("validation_strict", "Simulation only", True)]:
        a = sum((r[col] != val) if neg else (r[col] == val) for r in f); b = sum((r[col] != val) if neg else (r[col] == val) for r in h)
        p = fisher_exact([[a, len(f) - a], [b, len(h) - b]])[1]
        cells.append(f"{a}/{len(f)} vs {b}/{len(h)}, p = {p:.3f}")
    P(f"| {label} | {len(f)} / {len(h)} | " + " | ".join(cells) + " |")


sens("Primary (all 39)", rows)
sens("(a) Only papers with a physical platform (excl. Abstract/Unspecified and sensor-free)", [r for r in rows if r["platform_clean"] != "Abstract / Unspecified" and r["s_none"] != "1"])
sens("(a') Only papers modeling a human role", [r for r in rows if r["human_role_modelled"] == "Y"])
sens("(b) Only papers with RP ≥ 2", [r for r in rows if int(r["rp"]) >= 2])
blind = {r["ref_N"]: r["blind_mode"] for r in csv.DictReader(open("data/reliability_blind_codes.csv", encoding="utf-8"))}
mapb = {"T": TELE, "S": SUP, "C": SHR, "F": FA}
rows_b = [dict(r, mode_blind=mapb[blind[r["ref_N"]]]) for r in rows]
sens("(c) Mode re-coded with the blind AI codes (boundary cases)", rows_b, "mode_blind")
extra = [dict(rows[0], mode_clean=FA, validation_strict="Simulation only", validation_lenient="Simulation only") for _ in range(2)]
sens("(d) Adding excluded #70 and #83 as FA, simulation only (projection)", rows + extra)

open("data/analysis_output.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
